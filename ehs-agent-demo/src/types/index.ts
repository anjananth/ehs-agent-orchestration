// ---------------------------------------------------------------------------
// Scenario playback
// ---------------------------------------------------------------------------

/** Which panel states a step mutates. Consumed by the zustand store (prompt 06). */
export interface CanvasEffect {
  /** Node status overrides applied at this step (merged over previous state). */
  nodeStatus?: Partial<Record<AgentId, AgentStatus>>;
  /** Edges that should animate at this step: [source, target] pairs. */
  activeEdges?: Array<[AgentId, AgentId]>;
  /** Node to pulse once when the step lands. */
  pulse?: AgentId;
}

export interface GovernanceEffect {
  /** Audit events appended at this step. */
  appendEvents?: AuditEvent[];
  /** Governance checks to show (replaces the current check set). */
  checks?: GovernanceCheck[];
  /** Model badges lit at this step. */
  modelsInvoked?: FleetModelId[];
  /** Risk score to display, if scored at this step. */
  riskScore?: RiskScore;
  /** Open the human-in-the-loop approval gate. */
  openApproval?: 'pre-send' | 'nurse-escalation';
}

export interface ChatEffect {
  appendMessages?: ChatMessage[];
  /** Show a typing indicator before the message lands. */
  typing?: 'amal' | 'patient';
}

export interface ScenarioStep {
  id: string;
  order: number;
  /** Short headline, e.g. "Discharge trigger". */
  title: string;
  /** Presenter-facing narration of what's happening. */
  description: string;
  /** Milliseconds this step holds at 1x before auto-advancing. */
  durationMs: number;
  /** If set, auto-play halts here until a human action resolves it. */
  requiresHuman?: HumanAction;
  /** Marks the alternative branch (patient didn't respond → Hamda). */
  branch?: 'main' | 'fallback';
  canvasEffect?: CanvasEffect;
  governanceEffect?: GovernanceEffect;
  chatEffect?: ChatEffect;
  /** Case-bundle mutations (e.g. agent creates a ServiceRequest). */
  bundleEffect?: BundleEffect;
  /** Effects applied once the human action for this step has been taken. */
  onResolve?: StepEffects;
  /** Effects applied if the human rejects (gate stays open; presenter can still approve). */
  onReject?: StepEffects;
}

export type HumanAction = 'approve-message' | 'nurse-acknowledge';

export interface BundleEffect {
  addServiceRequest?: ServiceRequestItem;
}

export interface StepEffects {
  canvasEffect?: CanvasEffect;
  governanceEffect?: GovernanceEffect;
  chatEffect?: ChatEffect;
  bundleEffect?: BundleEffect;
}
