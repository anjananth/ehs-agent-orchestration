/**
 * Shared domain types for the EHS orchestration & governance demo.
 * Everything here is deliberately lightweight — readable by a business
 * audience, not a full FHIR R4 or watsonx schema.
 */

import type { ModelColourToken } from '@/styles/tokens';

// ---------------------------------------------------------------------------
// Agents & orchestration
// ---------------------------------------------------------------------------

export type AgentKind =
  | 'orchestrator'
  | 'system-of-record'
  | 'patient-facing'
  | 'nursing-workforce'
  | 'contact-centre'
  | 'orchestrated-agent';

export type AgentStatus = 'idle' | 'active' | 'awaiting-approval' | 'complete' | 'not-built';

export interface Agent {
  id: AgentId;
  name: string;
  /** Short line under the name on the canvas node. */
  subtitle: string;
  vendor: string;
  kind: AgentKind;
  status: AgentStatus;
  /** What this agent/system is — shown in the node detail drawer. */
  description: string;
  /** Role it plays in *this* scenario (drawer copy). */
  roleInScenario?: string;
}

export type AgentId =
  | 'orchestrator'
  | 'cerner'
  | 'care-continuity'
  | 'amal'
  | 'maitha'
  | 'hamda'
  | 'uc-referral'
  | 'uc-revenue'
  | 'uc-encounter'
  | 'uc-regulatory';

// ---------------------------------------------------------------------------
// Model fleet
// ---------------------------------------------------------------------------

export type Sovereignty = 'in-region' | 'external';

export type FleetModelId = 'sovereign-arabic' | 'granite' | 'medgemma' | 'classical-ml' | 'frontier';

export interface FleetModel {
  id: FleetModelId;
  /** Display name, e.g. "Jais 2". */
  name: string;
  /** Provider / origin, e.g. "G42 / Inception". */
  provider: string;
  /** Role in the fleet, e.g. "Sovereign Arabic dialogue". */
  role: string;
  sovereignty: Sovereignty;
  /** Where inference actually executes — the real sovereignty fact. */
  inferenceLocation: string;
  /** Key into tokens.model — drives badge colour everywhere. */
  colourToken: ModelColourToken;
  /** One-line "why this model" justification shown on every badge. */
  why: string;
  /** How it's used in the post-discharge scenario. */
  useInScenario: string;
}

// ---------------------------------------------------------------------------
// FHIR-lite clinical resources (readable, not full R4)
// ---------------------------------------------------------------------------

export interface Patient {
  /** Fictional identifier — never a real MRN. */
  id: string;
  name: string;
  nameArabic: string;
  age: number;
  sex: 'F' | 'M';
  preferredLanguage: 'ar' | 'en';
}

export interface Encounter {
  id: string;
  patientId: string;
  class: 'inpatient';
  specialty: string;
  facility: string;
  admitted: string; // ISO date
  discharged: string; // ISO date-time
  dischargeDisposition: string;
  primaryDiagnosis: string;
  /** Source event that triggered orchestration — narrative accuracy. */
  triggerEvent: 'ADT^A03';
}

export interface CarePlan {
  id: string;
  encounterId: string;
  title: string;
  goals: string[];
  instructions: string[];
}

export interface MedicationRequestItem {
  id: string;
  medication: string;
  previousDose: string;
  newDose: string;
  route: string;
  frequency: string;
  /** Why the dose changed — this is the detail the policy check guards. */
  reason: string;
  status: 'active';
}

export interface ServiceRequestItem {
  id: string;
  code: string;
  display: string;
  specialty: string;
  priority: 'routine' | 'urgent';
  /** Human-readable due window, e.g. "within 7 days". */
  dueWithin: string;
  scheduledFor?: string; // ISO date
  requestedBy: string;
  status: 'active' | 'completed';
  /** Set when the request was generated by the agent, not a clinician. */
  createdByAgent?: boolean;
}

export interface DischargeBundle {
  patient: Patient;
  encounter: Encounter;
  carePlan: CarePlan;
  medicationRequests: MedicationRequestItem[];
  serviceRequests: ServiceRequestItem[];
}

export interface ServiceRequestInput {
  patientId: string;
  code: string;
  display: string;
  specialty: string;
  priority: 'routine' | 'urgent';
  dueWithin: string;
  requestedBy: string;
}

