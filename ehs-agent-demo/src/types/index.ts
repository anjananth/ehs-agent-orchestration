// ---------------------------------------------------------------------------
// Governance
// ---------------------------------------------------------------------------

export type GovernanceCheckStatus = 'pass' | 'pending' | 'fail';

export interface GovernanceCheck {
  id: string;
  label: string;
  status: GovernanceCheckStatus;
  detail: string;
  /** Policy reference — makes the chip feel regulator-readable. */
  policyRef?: string;
}

export type AuditActor =
  | 'Cerner Millennium'
  | 'Orchestrator'
  | 'Care Continuity Agent'
  | 'watsonx.governance'
  | 'Model router'
  | 'Agentic Control Plane'
  | 'Amal'
  | 'Patient'
  | 'Nurse — Maitha queue'
  | 'Hamda';

export type AuditSeverity = 'info' | 'pass' | 'pending' | 'fail';

export interface AuditEvent {
  id: string;
  /** ISO timestamp; fixtures use a fixed base time and offsets. */
  timestamp: string;
  actor: AuditActor;
  action: string;
  detail: string;
  severity: AuditSeverity;
  relatedModel?: FleetModelId;
  /** Populated on human decisions so the export shows who/what approved. */
  humanDecision?: 'approved' | 'rejected' | 'acknowledged';
}

export interface AuditTrail {
  caseId: string;
  patientId: string;
  exportedAt: string;
  events: AuditEvent[];
  checks: GovernanceCheck[];
  modelsInvoked: FleetModelId[];
}

